-- WebDoji database schema (reconstructed from the queries in /model)
CREATE DATABASE IF NOT EXISTS dojin_nodejs CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE dojin_nodejs;

CREATE TABLE IF NOT EXISTS loaisanpham (
  ID INT AUTO_INCREMENT PRIMARY KEY,
  Ten VARCHAR(255) NOT NULL,
  NgayThem DATETIME DEFAULT CURRENT_TIMESTAMP,
  update_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  showw TINYINT(1) NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS xuatxu (
  ID INT AUTO_INCREMENT PRIMARY KEY,
  XuatXu VARCHAR(255) NOT NULL,
  NgayThem DATETIME DEFAULT CURRENT_TIMESTAMP,
  update_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  showw TINYINT(1) NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS sanpham (
  ID INT AUTO_INCREMENT PRIMARY KEY,
  ID_LoaiSanPham INT NOT NULL,
  imgName VARCHAR(255),
  Image LONGTEXT,               -- image stored as base64 text
  TenSanPham VARCHAR(255) NOT NULL,
  GiaNhap BIGINT NOT NULL DEFAULT 0,
  GiaBan BIGINT NOT NULL DEFAULT 0,
  SoLuong INT NOT NULL DEFAULT 0,
  NgayNhap DATETIME DEFAULT CURRENT_TIMESTAMP,
  update_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  XuatXu INT NOT NULL,
  show_lsp TINYINT(1) NOT NULL DEFAULT 1,
  show_xx TINYINT(1) NOT NULL DEFAULT 1,
  show_sp TINYINT(1) NOT NULL DEFAULT 1,
  FOREIGN KEY (ID_LoaiSanPham) REFERENCES loaisanpham(ID),
  FOREIGN KEY (XuatXu) REFERENCES xuatxu(ID)
);

CREATE TABLE IF NOT EXISTS taikhoan_admin (
  ID INT AUTO_INCREMENT PRIMARY KEY,
  TenTK VARCHAR(100) NOT NULL UNIQUE,
  MatKhau VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS taikhoan_kh (
  ID INT AUTO_INCREMENT PRIMARY KEY,
  TenTK VARCHAR(100) NOT NULL UNIQUE,
  MatKhau VARCHAR(255) NOT NULL,
  TrangThai TINYINT(1) NOT NULL DEFAULT 1,   -- 1 = active, 0 = locked
  NgayDK DATETIME DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS trangthai (
  ID INT PRIMARY KEY,
  TenTT VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS hoadon (
  ID INT AUTO_INCREMENT PRIMARY KEY,
  IDTK INT NOT NULL,
  TenKH VARCHAR(255),
  DiaChi VARCHAR(500),
  SDT VARCHAR(20),
  TongTien BIGINT NOT NULL DEFAULT 0,
  NgayMua DATETIME DEFAULT CURRENT_TIMESTAMP,
  GhiChu VARCHAR(500),
  TrangThai INT NOT NULL DEFAULT 1,
  FOREIGN KEY (IDTK) REFERENCES taikhoan_kh(ID),
  FOREIGN KEY (TrangThai) REFERENCES trangthai(ID)
);

CREATE TABLE IF NOT EXISTS cthoadon (
  ID INT AUTO_INCREMENT PRIMARY KEY,
  ID_HoaDon INT NOT NULL,
  IDSanPham INT NOT NULL,
  SoLuong INT NOT NULL,
  ThanhTien BIGINT NOT NULL,
  FOREIGN KEY (ID_HoaDon) REFERENCES hoadon(ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS giohang (
  ID INT AUTO_INCREMENT PRIMARY KEY,
  IDTK INT NOT NULL,
  IDSanPham INT NOT NULL,
  TenSanPham VARCHAR(255),
  XuatXu VARCHAR(255),
  DonGia BIGINT NOT NULL,
  SoLuong INT NOT NULL,
  ThanhTien BIGINT NOT NULL
);

